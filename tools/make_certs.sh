#!/usr/bin/env bash
# make_certs.sh [outdir] - generate the PKI for s0P0wn3d v0.2
#
# Creates:
#   <outdir>/ca.key / ca.crt          self-signed root CA (keep ca.key OFFLINE)
#   <outdir>/server.key / server.crt  controller certificate, signed by the CA
#   implant/cert_pin.h                C header with the server cert SHA-256 pin
#
# The implant does not do CA chain validation in v0.2: it pins the server
# certificate's SHA-256 fingerprint directly. Rotating certs = re-run this
# script and rebuild the implant.

set -euo pipefail

OUT="${1:-certs}"
DAYS=825
mkdir -p "$OUT"

openssl req -x509 -newkey rsa:4096 -nodes \
    -keyout "$OUT/ca.key" -out "$OUT/ca.crt" \
    -days "$DAYS" -subj "//CN=s0P0wn3d local CA"

openssl req -newkey rsa:2048 -nodes \
    -keyout "$OUT/server.key" -out "$OUT/server.csr" \
    -subj "//CN=s0p0wn3d-controller"

printf 'subjectAltName=DNS:localhost,IP:127.0.0.1\n' > "$OUT/server.ext"

openssl x509 -req -in "$OUT/server.csr" \
    -CA "$OUT/ca.crt" -CAkey "$OUT/ca.key" -CAcreateserial \
    -out "$OUT/server.crt" -days "$DAYS" -extfile "$OUT/server.ext"

THUMB_HEX=$(openssl x509 -in "$OUT/server.crt" -outform DER | openssl dgst -sha256 | awk '{print $NF}')
BYTES=$(echo "$THUMB_HEX" | sed 's/../0x&, /g' | sed 's/, $//')

{
    echo "/* Generated by tools/make_certs.sh - do not edit, regenerate. */"
    echo "#ifndef CERT_PIN_H"
    echo "#define CERT_PIN_H"
    echo "static const unsigned char SERVER_CERT_SHA256[32] = { $BYTES };"
    echo "#endif"
} > implant/cert_pin.h

rm -f "$OUT/server.csr" "$OUT/server.ext" "$OUT/ca.srl"

echo "[+] CA:     $OUT/ca.crt (keep ca.key private)"
echo "[+] Server: $OUT/server.crt + $OUT/server.key"
echo "[+] Pin:    implant/cert_pin.h ($THUMB_HEX)"
